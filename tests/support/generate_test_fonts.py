"""Regenerate font_test_data.h with fontTools; no installed or third-party font is copied."""

from io import BytesIO
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen


def make_font(style, weight, advance, italic=False):
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder([".notdef", "space", "A"])
    builder.setupCharacterMap({32: "space", 65: "A"})
    glyphs = {}
    for name in [".notdef", "space", "A"]:
        pen = TTGlyphPen(None)
        if name != "space":
            pen.moveTo((50, 0))
            pen.lineTo((advance // 2, 700))
            pen.lineTo((advance - 50, 0))
            pen.closePath()
        glyphs[name] = pen.glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (advance, 50 if name != "space" else 0) for name in glyphs})
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupNameTable({
        "familyName": "HuxerUI Test",
        "styleName": style,
        "uniqueFontIdentifier": "HuxerUI-Test-" + style,
        "fullName": "HuxerUI Test " + style,
        "psName": "HuxerUI-Test-" + style,
        "typographicFamily": "HuxerUI Test",
        "typographicSubfamily": style,
        "version": "Version 1.0",
    })
    builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200,
                    usWeightClass=weight, fsSelection=1 if italic else 32 if weight == 700 else 64)
    builder.setupPost(italicAngle=-12 if italic else 0)
    builder.setupMaxp()
    builder.font["head"].macStyle = 2 if italic else 1 if weight == 700 else 0
    builder.font["head"].created = builder.font["head"].modified = 3400000000
    builder.font.recalcTimestamp = False
    result = BytesIO()
    builder.save(result)
    return result.getvalue()


lines = ["// Generated by generate_test_fonts.py from original geometric glyphs.",
         "#pragma once", "", "#include <array>", "", "namespace huxerui::test {", ""]
for style, weight, advance, italic in [("Regular", 400, 500, False), ("Bold", 700, 800, False),
                                       ("Italic", 400, 650, True)]:
    data = make_font(style, weight, advance, italic)
    lines.append(f"inline constexpr std::array<unsigned char, {len(data)}> test_font_{style.lower()}{{{{")
    for start in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{value:02x}" for value in data[start:start + 20]) + ",")
    lines.extend(["}};", ""])
lines.append("} // namespace huxerui::test")
Path(__file__).with_name("font_test_data.h").write_text("\n".join(lines) + "\n")
